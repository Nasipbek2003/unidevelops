/** Неразрывные пробелы в ценах: разряд («1 200») и перед «сом». Копирайтер мог поставить обычные. */
export function nb(s: string): string {
  return s
    .replace(/(\d)[   ](?=\d{3}(?!\d))/g, "$1 ")
    .replace(/(\d)[   ]+(?=сом)/g, "$1 ");
}

